/** 사이 역 좌표: 같은 호선에서 앞뒤로 가장 가까운 기준역 사이에 고르게 */
export function layout() {
  const xy = { ...ANCHOR };
  for (const list of Object.values(LINES)) {
    const idx = list.map((n, i) => (xy[n] ? i : -1)).filter((i) => i >= 0);
    for (let k = 0; k < idx.length - 1; k++) {
      const a = idx[k], b = idx[k + 1];
      const [x1, y1] = xy[list[a]], [x2, y2] = xy[list[b]];
      for (let i = a + 1; i < b; i++) {
        const t = (i - a) / (b - a);
        if (!xy[list[i]]) xy[list[i]] = [x1 + (x2 - x1) * t, y1 + (y2 - y1) * t];
      }
    }
  }
  return xy;
}

function check(xy) {
  const names = Object.keys(xy);
  const all = new Set(Object.values(LINES).flat());
  const missing = [...all].filter((n) => !xy[n]);
  const close = [];
  for (let i = 0; i < names.length; i++) for (let j = i + 1; j < names.length; j++) {
    const [a, b] = [xy[names[i]], xy[names[j]]];
    const d = Math.hypot(a[0] - b[0], a[1] - b[1]);
    if (d < 1.2) close.push(`${names[i]}·${names[j]} ${d.toFixed(2)}`);
  }
  const near = [];
  for (const [id, list] of Object.entries(LINES)) for (let i = 0; i < list.length - 1; i++) {
    const [x1, y1] = xy[list[i]], [x2, y2] = xy[list[i + 1]];
    for (const n of names) {
      if (n === list[i] || n === list[i + 1]) continue;
      const [px, py] = xy[n]; const dx = x2 - x1, dy = y2 - y1;
      const t = Math.max(0, Math.min(1, ((px - x1) * dx + (py - y1) * dy) / (dx * dx + dy * dy || 1)));
      const d = Math.hypot(px - x1 - t * dx, py - y1 - t * dy);
      if (d < 0.55) near.push(`${id}호선 ${list[i]}–${list[i + 1]} 위에 ${n} ${d.toFixed(2)}`);
    }
  }
  return { count: names.length, missing, close, near };
}

